// payrollCold and payrollWarm are the layers of the pack `payroll` (plan 2-29 D4):
// one-demand with the employment module in its payroll form, then its own data
// layer, then, for the warm set, the solver's table for the cold set.
var (
	payrollCold = []string{"base.toml", "demand.toml", "one-demand.toml", "overlay/employment.toml", "overlay/chain-payroll.toml"}
	payrollWarm = append(append([]string{}, payrollCold...), "warm-payroll.toml")
)

const payrollWarmPath = "testdata/chains/warm-payroll.toml"

// renderWarmDocument writes a steady-state table as a warm-start document, the
// layout of the other warm-*.toml files (a region's wage, pool and seed prices,
// then one table per group). It is the generator of warm-payroll.toml: the file
// is never edited by hand (FR-REF-007, FR-REF-043).
func renderWarmDocument(ws economysim.WarmStart) []byte {
	var b strings.Builder
	b.WriteString("# Generated by TestPacks_Payroll with -update from SolveSteadyState of the cold layers of the pack\n" +
		"# `payroll` (payrollCold in payroll_pack_test.go). Never edit by hand (FR-REF-007, FR-REF-043).\n")
	for _, w := range ws.Wages {
		fmt.Fprintf(&b, "[warm_start.region.%s]\nwage = %d\n", w.Region, w.Wage)
		for _, p := range ws.Pools {
			if p.Region == w.Region {
				fmt.Fprintf(&b, "pool = %d\n", p.Money)
			}
		}
		fmt.Fprintf(&b, "[warm_start.region.%s.price]\n", w.Region)
		for _, p := range ws.Prices {
			if p.Region == w.Region {
				fmt.Fprintf(&b, "%s = %d\n", p.Commodity, p.Price)
			}
		}
		for _, g := range ws.Groups {
			if g.Region != w.Region {
				continue
			}
			fmt.Fprintf(&b, "[warm_start.region.%s.group.%s]\nmoney = %d\n", w.Region, g.Role, g.Money)
			if len(g.Stock) > 0 {
				items := make([]string, len(g.Stock))
				for i, it := range g.Stock {
					items[i] = fmt.Sprintf("{ commodity = %q, quantity = %d }", it.Commodity, it.Quantity)
				}
				fmt.Fprintf(&b, "stock = [ %s ]\n", strings.Join(items, ", "))
			}
			if len(g.Jobs) > 0 {
				jobs := make([]string, len(g.Jobs))
				for i, j := range g.Jobs {
					jobs[i] = fmt.Sprintf("{ recipe = %q, in_progress = %d }", j.Recipe, j.InProgressBP)
				}
				fmt.Fprintf(&b, "jobs = [ %s ]\n", strings.Join(jobs, ", "))
			}
		}
		b.WriteString("\n")
	}
	return []byte(b.String())
}

// TestPacks_Payroll verifies the pack `payroll` (plan 2-29 Phase 5): its layers
// load and validate with the employment module on; the solver reports no payroll
// diagnostic; the households of every group are the census the payroll-aware
// solver balances (so the want data and the durability fix the discretionary
// roles, and no count is cut by hand); the static IncomeBP of every group is at
// least 8 000 and the spread at most 1.5 (FR-REF-041); the warm-start document is
// byte-identical to the table the solver renders for the cold layers
// (FR-REF-043; -update rewrites it from the solver); the static tool margin holds
// (FR-REF-044); and a world built from it audits clean over a few ticks. The
// pack's count claim is not tested here: FR-REF-045 is TestScenarioChain_Claim.
//
// Requirement: FR-REF-041, FR-REF-043, FR-REF-044, FR-REF-007
func TestPacks_Payroll(t *testing.T) {
	t.Parallel()
	if testing.Short() {
		t.Skip("integration test, skipped with -short")
	}
	cold := loadValidPack(t, payrollCold...)
	if cold.Modules.Employment == nil {
		t.Fatalf("Modules.Employment of the pack payroll = nil, want the module on")
	}
	st, err := economysim.SolveSteadyState(context.Background(), cold)
	if err != nil {
		t.Fatalf("SolveSteadyState(payroll) error = %v, want nil", err)
	}
	if st.Report.PayrollInfeasible != nil {
		t.Fatalf("PayrollInfeasible = %+v, want nil: a pack is never made from an infeasible share", st.Report.PayrollInfeasible)
	}

	// Census: every group holds the households the solver balances (exact, not a tolerance).
	lo, hi, loAt, hiAt := int64(-1), int64(0), "", ""
	var total int64
	for _, r := range st.Report.Census {
		if r.Role == "" {
			continue
		}
		key := r.Region + "/" + r.Role
		total += r.Households
		if r.Households != r.Balanced {
			t.Errorf("census %s: households = %d, balanced = %d, want equal (the count is the solver's, not cut by hand)", key, r.Households, r.Balanced)
		}
		if !r.HasIncome {
			t.Errorf("census %s has no IncomeBP, want one (no exception is listed for the pack payroll)", key)
			continue
		}
		if lo < 0 || r.IncomeBP < lo {
			lo, loAt = r.IncomeBP, key
		}
		if r.IncomeBP > hi {
			hi, hiAt = r.IncomeBP, key
		}
	}
	if total != 600 {
		t.Errorf("households of the pack payroll = %d, want 600 (the size of one-demand at T6: 223 cooks, 377 others)", total)
	}
	if lo < incomeGateMin {
		t.Errorf("least IncomeBP = %d (%s), want >= %d", lo, loAt, incomeGateMin)
	}
	if hi*incomeGateSpreadDen > lo*incomeGateSpreadNum {
		t.Errorf("greatest IncomeBP = %d (%s), want <= 1.5 * %d (%s)", hi, hiAt, lo, loAt)
	}

	// Warm start: byte equality with the solver's table.
	want := renderWarmDocument(st.Table)
	if *updateFlag {
		if err := os.WriteFile(filepath.FromSlash(payrollWarmPath), want, 0o644); err != nil {
			t.Fatalf("write %s: %v", payrollWarmPath, err)
		}
	}
	got, err := os.ReadFile(filepath.FromSlash(payrollWarmPath))
	if err != nil {
		t.Fatalf("read %s: %v", payrollWarmPath, err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from the table SolveSteadyState renders for the cold layers; regenerate it with -update (never by hand)", payrollWarmPath)
	}

	// Static tool margin (FR-REF-044). Reference price: the payroll-free solver's seed price of
	// the commodity (the price of the pack one-demand), as the plan's formula reads it.
	refSt, err := economysim.SolveSteadyState(context.Background(), loadPack(t, packOneDemandCold...))
	if err != nil {
		t.Fatalf("SolveSteadyState(one-demand) error = %v, want nil", err)
	}
	price := func(s economysim.WarmStart, commodity string) int64 {
		for _, p := range s.Prices {
			if p.Commodity == commodity {
				return int64(p.Price)
			}
		}
		t.Fatalf("no seed price for %s", commodity)
		return 0
	}
	yield := func(recipe, commodity string) int64 {
		for _, r := range cold.Recipes {
			if r.ID != recipe {
				continue
			}
			for _, o := range r.Outputs {
				if o.Commodity == commodity {
					return int64(o.Quantity)
				}
			}
		}
		t.Fatalf("recipe %s has no output %s", recipe, commodity)
		return 0
	}
	var durability int64
	for _, c := range cold.Commodities {
		if c.ID == "tool_b" {
			durability = c.Durability
		}
	}
	tool, ref := price(st.Table, "tool_b"), price(refSt.Table, "prepared")
	gain := yield("prepare", "prepared") - yield("prepare_basic", "prepared")
	if durability <= 0 || gain <= 0 || ref <= 0 {
		t.Fatalf("durability = %d, yield gain = %d, reference = %d, want all positive", durability, gain, ref)
	}
	// break-even = (tool / durability) / gain, at most 50% of ref at the solver's price, 100% at three times it;
	// cross-multiplied so no division rounds: tool*100 <= limit*ref*durability*gain.
	for _, c := range []struct{ mult, limit int64 }{{1, 50}, {3, 100}} {
		if c.mult*tool*100 > c.limit*ref*durability*gain {
			t.Errorf("tool margin at %dx the tool price: break-even %d/%d/%d is above %d%% of the reference price %d of prepared (FR-REF-044)", c.mult, c.mult*tool, durability, gain, c.limit, ref)
		}
	}

	// A world built from the pack audits clean over a few ticks.
	w, err := economysim.NewWorld(loadValidPack(t, payrollWarm...), economysim.WithAudit(), economysim.WithSeed(1))
	if err != nil {
		t.Fatalf("NewWorld(payroll) error = %v, want nil", err)
	}
	for i := range 10 {
		if err := w.Step(); err != nil {
			t.Fatalf("Step at tick %d error = %v, want nil", i, err)
		}
	}
	if err := w.Audit(); err != nil {
		t.Errorf("Audit after 10 ticks = %v, want nil", err)
	}
}
